const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('pets', {
  get: () => ipcRenderer.invoke('settings:get'),
  preset: (kind) => ipcRenderer.invoke('settings:preset', kind),
  savePet: (p) => ipcRenderer.invoke('settings:save-pet', p),
  addPet: (kind) => ipcRenderer.invoke('settings:add-pet', kind),
  removePet: (id) => ipcRenderer.invoke('settings:remove-pet', id),
  setHidden: (id, on) => ipcRenderer.invoke('settings:set-hidden', id, on),
  testPet: (id) => ipcRenderer.invoke('settings:test-pet', id),
  openApp: (id) => ipcRenderer.invoke('settings:open-app', id),
  chatNow: () => ipcRenderer.invoke('settings:chat-now'),
  saveGlobal: (g) => ipcRenderer.invoke('settings:save-global', g),
  pickFile: () => ipcRenderer.invoke('settings:pick-file'),
  updateCheck: () => ipcRenderer.invoke('settings:update-check'),
  updateInstall: () => ipcRenderer.invoke('settings:update-install'),
  onState: (cb) => ipcRenderer.on('settings:state', (_e, s) => cb(s)),
  onFocus: (cb) => ipcRenderer.on('settings:focus', (_e, id) => cb(id)),
  onCreate: (cb) => ipcRenderer.on('settings:create', () => cb()),
  installedApps: () => ipcRenderer.invoke('settings:installed-apps'),
  connectApp: (id, app) => ipcRenderer.invoke('settings:connect-app', id, app),
  exportPets: (id) => ipcRenderer.invoke('settings:export-pets', id || null),
  importPets: () => ipcRenderer.invoke('settings:import-pets'),
  openLink: (url) => ipcRenderer.invoke('settings:open-link', String(url)),
  hookStatus: () => ipcRenderer.invoke('settings:hook-status'),
  hookInstall: () => ipcRenderer.invoke('settings:hook-install'),
  copy: (text) => ipcRenderer.invoke('settings:copy', String(text).slice(0, 4000)),
});
